    def save(self, path: str, h: int) -> None:
        """Save a full checkpoint of the current training state.

        Saved dict keys:
          * ``score_net``   – live network state dict
          * ``ema``         – EMA state dict (shadow + decay)
          * ``optimizer``   – optimiser state dict
          * ``teachers``    – {h: state_dict} for all frozen teachers
          * ``global_step`` – global gradient-step counter
          * ``h``           – current horizon index
          * ``config``      – training config dict

        Args:
            path: File path (will be created, parent dirs must exist).
            h:    Current training horizon index (stored in checkpoint).
        """
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        checkpoint = {
            "score_net": self.score_net.state_dict(),
            "ema": self.ema.state_dict(),
            "optimizer": self.optimizer.state_dict(),
            "teachers": {
                stage: net.state_dict()
                for stage, net in self._teachers.items()
            },
            "global_step": self._global_step,
            "h": h,
            "config": self.config,
        }
        torch.save(checkpoint, path)
        logger.debug("Checkpoint written to %s  (h=%d, step=%d)", path, h, self._global_step)

    def load(self, path: str) -> None:
        """Restore trainer state from a checkpoint written by :meth:`save`.

        The score network, EMA shadow, optimizer, frozen teachers, and step
        counter are all restored.  The model architecture must match exactly.

        Args:
            path: Path to the checkpoint file.

        Raises:
            FileNotFoundError: If *path* does not exist.
            KeyError:          If the checkpoint is missing expected keys.
        """
        if not os.path.isfile(path):
            raise FileNotFoundError(f"Checkpoint not found: {path}")

        checkpoint = torch.load(path, map_location="cpu")

        self.score_net.load_state_dict(checkpoint["score_net"])
        self.ema.load_state_dict(checkpoint["ema"])
        self.optimizer.load_state_dict(checkpoint["optimizer"])
        self._global_step = int(checkpoint.get("global_step", 0))

        # Restore frozen teachers.  We need a reference model for architecture;
        # we clone the live score_net for each teacher and load its state.
        for stage_str, sd in checkpoint.get("teachers", {}).items():
            stage = int(stage_str)
            frozen = copy.deepcopy(self.score_net)
            frozen.load_state_dict(sd)
            frozen.eval()
            frozen.requires_grad_(False)
            self._teachers[stage] = frozen

        logger.info(
            "Checkpoint loaded from %s  (h=%s, global_step=%d)",
            path,
            checkpoint.get("h", "?"),
            self._global_step,
        )

