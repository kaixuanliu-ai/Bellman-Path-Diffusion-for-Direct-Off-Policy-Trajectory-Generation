"""
Stagewise Bellman Path Diffusion Trainer (Algorithm 1).

Implements the training procedure from:
  "Bellman Path Diffusion for Direct Off-Policy Trajectory Generation"

Algorithm 1 — Bellman Path Diffusion Training with Suffix Replay:

    For h = 1, ..., H:
      a. Freeze teacher score s_{θ̄, h-1} and its clean reverse generator.
      b. Initialise replay buffer R_{h-1} keyed by exact x'.
      c. Refresh R_{h-1} by sampling teacher suffixes.
      d. Repeat for config['steps_per_horizon'] gradient steps:
           - Sample (s, a, r, s') ~ D,  a' ~ π_e(·|s').
           - Sample t ~ p_T,  C ~ Bernoulli(γ).
           - If C=0 or h=1: use stop branch  (score target = q_{t|0} analytic).
           - Else: retrieve/generate teacher suffix from replay; use push branch.
           - Update θ with λ(t) ‖ s_θ(z_t | x, h) - u ‖².
      e. Freeze/EMA-copy horizon-h score to serve as teacher for stage h+1.

Score-matching target u (Eq. 43, BPD paper):
    stop branch  (C=0 or h=1):
        z   = q-sample of stop_h(y) at time t
        u   = analytic score of q_{t|0}(z | stop_h(y))
            = -(z - α_t * stop_h(y)) / σ_t²
    push branch  (C=1, h>1):
        w_{suffix} = teacher-generated suffix  (shape (h-1, token_dim))
        w_push     = push_h(y, w_{suffix})     (shape (h,   token_dim))
        z          = q-sample of w_push at time t
        u          = analytic score of q_{t|0}(z | w_push)
                   = -(z - α_t * w_push) / σ_t²

Loss weighting λ(t):
    Following Ho et al. 2020 the simple (unweighted) loss is used (λ=1).
    Callers may override by passing a custom ``loss_fn``.

EMA:
    After each gradient step the EMA of θ is maintained.  At the end of each
    stage the EMA shadow copy is frozen and stored as the teacher for the next
    stage.

Replay buffer (Section 6):
    For each x' = (s', a') encountered during training, the buffer stores a
    clean (noise-free) suffix W_+ generated by the frozen teacher at the
    *previous* horizon h-1.  The teacher suffix is re-corrupted online at
    time t to obtain the training target (Proposition 1 / Eq. 50).

Config keys
-----------
gamma               : float  – geometric discount / Bernoulli parameter
H                   : int    – maximum horizon (number of stages)
steps_per_horizon   : int    – gradient steps per stage
batch_size          : int    – transitions per gradient step
log_freq            : int    – log every N steps
save_freq           : int    – checkpoint every N steps
lr                  : float  – Adam learning rate (used only if no optimiser passed)
ema_decay           : float  – EMA decay rate (e.g. 0.9999)
replay_buffer_size  : int    – max entries per per-horizon replay buffer
diffusion_steps     : int    – T, number of diffusion steps  (must match schedule)
"""

