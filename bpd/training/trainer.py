# ---------------------------------------------------------------------------
# EMA helper
# ---------------------------------------------------------------------------


class EMAModel:
    """Exponential Moving Average of model parameters.

    Maintains a shadow copy of ``model``'s parameters and updates it after
    every training step:

        shadow_p = decay * shadow_p + (1 - decay) * param_p

    The shadow copy is used as the frozen teacher network.

    Args:
        model:  The *live* model whose parameters are being tracked.
        decay:  EMA decay rate (e.g. 0.9999).
    """

    def __init__(self, model: nn.Module, decay: float = 0.9999) -> None:
        self.decay = decay
        # Deep-copy once so shadow always has the same architecture.
        self.shadow: nn.Module = copy.deepcopy(model)
        self.shadow.requires_grad_(False)

    @torch.no_grad()
    def step(self, model: nn.Module) -> None:
        """Update shadow parameters from *model*'s current parameters."""
        for shadow_p, model_p in zip(
            self.shadow.parameters(), model.parameters()
        ):
            shadow_p.data.mul_(self.decay).add_(
                model_p.data, alpha=1.0 - self.decay
            )

    def state_dict(self) -> dict:
        return {"shadow": self.shadow.state_dict(), "decay": self.decay}

    def load_state_dict(self, sd: dict) -> None:
        self.shadow.load_state_dict(sd["shadow"])
        self.decay = sd["decay"]


# ---------------------------------------------------------------------------
# Loss function type alias
# ---------------------------------------------------------------------------

# A loss function maps (pred, target, t) → scalar loss tensor.
# ``pred`` and ``target`` are both (B, h, token_dim).
# ``t`` is (B,) long.  Default: simple MSE, weight λ(t) = 1.
LossFn = Callable[[Tensor, Tensor, Tensor], Tensor]


def _default_loss_fn(pred: Tensor, target: Tensor, t: Tensor) -> Tensor:
    """Simple unweighted MSE  E[ ‖ pred - target ‖² ] (Ho et al. 2020 Eq. 14)."""
    return ((pred - target) ** 2).mean()


