# BellmanPathDiffusionTrainer
# ---------------------------------------------------------------------------


class BellmanPathDiffusionTrainer:
    """Stagewise BPD trainer implementing Algorithm 1.

    Parameters
    ----------
    score_net:
        The trainable score / noise-prediction network s_θ.
        Must accept ``(z_t, x, t, h)`` where:
          * z_t  – (B, h, token_dim) noisy path
          * x    – (B, obs_dim + act_dim) conditioning
          * t    – (B,) long diffusion timesteps
          * h    – int horizon (same for all batch items)
        and return predicted noise ε of the same shape as z_t.
    diffusion:
        A :class:`~bpd.models.diffusion.BlockwiseDiffusion` instance that
        implements the forward corruption kernel and score targets.
    schedule:
        A noise schedule object (DDPMSchedule or VPSchedule).  Used to
        obtain T and schedule tensors.
    loss_fn:
        Callable ``(pred, target, t) -> scalar``.  If ``None`` the simple
        MSE loss is used.
    optimizer:
        Pre-built ``torch.optim.Optimizer`` bound to ``score_net``'s
        parameters.  If ``None`` an Adam optimiser is created from
        ``config['lr']``.
    ema:
        Pre-built :class:`EMAModel`.  If ``None`` one is created from
        ``config['ema_decay']``.
    config:
        Dictionary of hyper-parameters — see module docstring for keys.
    """

    # ------------------------------------------------------------------
    # Construction
    # ------------------------------------------------------------------

    def __init__(
        self,
        score_net: nn.Module,
        diffusion: BlockwiseDiffusion,
        schedule,  # DDPMSchedule | VPSchedule
        loss_fn: Optional[LossFn] = None,
        optimizer: Optional[Optimizer] = None,
        ema: Optional[EMAModel] = None,
        config: Optional[Dict] = None,
    ) -> None:
        self.score_net = score_net
        self.diffusion = diffusion
        self.schedule = schedule
        self.loss_fn: LossFn = loss_fn if loss_fn is not None else _default_loss_fn

        # ---- Config with sensible defaults ---------------------------------
        cfg: Dict = config or {}
        self.gamma: float = float(cfg.get("gamma", 0.99))
        self.H: int = int(cfg.get("H", 4))
        self.steps_per_horizon: int = int(cfg.get("steps_per_horizon", 100_000))
        self.batch_size: int = int(cfg.get("batch_size", 256))
        self.log_freq: int = int(cfg.get("log_freq", 1_000))
        self.save_freq: int = int(cfg.get("save_freq", 10_000))
        self.lr: float = float(cfg.get("lr", 3e-4))
        self.ema_decay: float = float(cfg.get("ema_decay", 0.9999))
        self.replay_buffer_size: int = int(cfg.get("replay_buffer_size", 50_000))
        # T is authoritative from the diffusion object; config key is informational.
        self.T: int = diffusion.T
        self.config = cfg

        # ---- Optimizer -----------------------------------------------------
        if optimizer is not None:
            self.optimizer: Optimizer = optimizer
        else:
            self.optimizer = torch.optim.Adam(
                score_net.parameters(), lr=self.lr
            )

        # ---- EMA -----------------------------------------------------------
        self.ema: EMAModel = ema if ema is not None else EMAModel(
            score_net, decay=self.ema_decay
        )

        # ---- Teacher registry --------------------------------------------
        # Frozen teacher nets, indexed by stage: self._teachers[h] is the
        # frozen EMA snapshot after training stage h.
        self._teachers: Dict[int, nn.Module] = {}

        # ---- Replay buffers -----------------------------------------------
        # self._replay_buffers[h] is R_{h-1} used during stage h training.
        self._replay_buffers: Dict[int, SuffixReplayBuffer] = {}

        # ---- Global step counter across all stages -------------------------
        self._global_step: int = 0

    # ------------------------------------------------------------------
    # Public training interface
    # ------------------------------------------------------------------

    def train_all_stages(
        self,
        dataset: TransitionDataset,
        eval_policy_fn: Callable[[Tensor], Tensor],
        device: torch.device,
        writer: Optional[SummaryWriter] = None,
    ) -> None:
        """Train all H horizon stages sequentially.

        For each stage h in {1, ..., H}, calls :meth:`train_stage` then
        freezes the resulting EMA as the teacher for stage h+1.

        Args:
            dataset:        Offline transition dataset D.
            eval_policy_fn: Callable ``(next_state: Tensor) -> Tensor``
                            implementing π_e.  Input shape ``(obs_dim,)``;
                            output shape ``(act_dim,)``.
            device:         Compute device.
            writer:         Optional TensorBoard SummaryWriter.
        """
        logger.info(
            "Starting BPD training: H=%d, steps_per_horizon=%d",
            self.H,
            self.steps_per_horizon,
        )
        for h in range(1, self.H + 1):
            logger.info("=== Stage h=%d / %d ===", h, self.H)
            metrics = self.train_stage(
                h=h,
                dataset=dataset,
                eval_policy_fn=eval_policy_fn,
                device=device,
                writer=writer,
            )
            logger.info(
                "Stage h=%d complete. Final loss: %.6f",
                h,
                metrics.get("final_loss", float("nan")),
            )

    def train_stage(
        self,
        h: int,
        dataset: TransitionDataset,
        eval_policy_fn: Callable[[Tensor], Tensor],
        device: torch.device,
        writer: Optional[SummaryWriter] = None,
    ) -> Dict[str, float]:
        """Train the score network for a single horizon stage h.

        Implements steps (a)–(d) of Algorithm 1.

        Args:
            h:              Current horizon index (1-based).
            dataset:        Offline transition dataset.
            eval_policy_fn: Evaluation policy π_e.
            device:         Compute device.
            writer:         Optional TensorBoard SummaryWriter.

        Returns:
            Dictionary with at least ``"final_loss"`` and ``"mean_loss"``.
        """
        if h < 1 or h > self.H:
            raise ValueError(f"h must be in [1, {self.H}]; got {h}")

        # Step (a): obtain frozen teacher (if h > 1)
        teacher_fn = self._teacher_score_fn(h)  # callable or None when h=1

        # Step (b)/(c): initialise and refresh replay buffer R_{h-1}
        token_dim: int = diffusion_token_dim(self.diffusion)
        if h > 1:
            # Suffix horizon for stage h is (h-1) tokens.
            buf = SuffixReplayBuffer(
                max_size=self.replay_buffer_size,
                suffix_horizon=h - 1,
                token_dim=token_dim,
            )
            self._replay_buffers[h] = buf
            n_refresh = min(self.replay_buffer_size, 4 * self.batch_size)
            logger.info(
                "Refreshing replay buffer for stage h=%d with %d samples ...",
                h,
                n_refresh,
            )
            self._refresh_replay_buffer(
                buffer=buf,
                h=h,
                dataset=dataset,
                teacher=teacher_fn,
                device=device,
                n_samples=n_refresh,
            )
            logger.info(
                "Replay buffer ready: %d entries", len(buf)
            )
        else:
            buf = None

        # Step (d): main training loop
        self.score_net.train()
        self.score_net.to(device)
        self.diffusion.to(device)

        loss_accum: float = 0.0
        n_logged: int = 0
        last_loss: float = float("nan")

        for local_step in range(1, self.steps_per_horizon + 1):
            self._global_step += 1

            # ---- Sample a batch of transitions from D ----------------------
            (
                states,       # (B, obs_dim)
                actions,      # (B, act_dim)
                rewards,      # (B,)
                next_states,  # (B, obs_dim)
                next_actions, # (B, act_dim)
            ) = self._sample_batch(dataset, eval_policy_fn, device)

            # ---- Sample t ~ Uniform{1,...,T} and C ~ Bernoulli(gamma) ------
            B = states.shape[0]
            t = torch.randint(1, self.T + 1, (B,), device=device, dtype=torch.long)
            C = torch.bernoulli(torch.full((B,), self.gamma, device=device))  # (B,)
            use_push = (C > 0.5) & (h > 1)  # (B,) bool: True → push branch

            # ---- Build clean path w and compute z_t, score target u --------
            w, x_cond = self._build_training_targets(
                h=h,
                rewards=rewards,
                next_states=next_states,
                next_actions=next_actions,
                states=states,
                actions=actions,
                use_push=use_push,
                replay_buf=buf,
                teacher_fn=teacher_fn,
                device=device,
            )
            # w      : (B, h, token_dim) – clean path
            # x_cond : (B, obs_dim + act_dim) – conditioning

            # Corrupt: z_t = α_t * w + σ_t * ε
            z_t = self.diffusion.q_sample_blockwise(w, t)  # (B, h, token_dim)

            # Analytic score target u = -(z_t - α_t * w) / σ_t²
            u = self.diffusion.blockwise_score_target(z_t, w, t)  # (B, h, token_dim)

            # ---- Forward pass through score network ------------------------
            noise_pred = self.score_net(z_t, x_cond, t, h)  # (B, h, token_dim)

            # Convert network noise prediction to score for loss:
            # score_pred = -ε_θ / σ_t
            sigma_t = self.diffusion.sqrt_one_minus_alphas_bar[t]  # (B,)
            while sigma_t.dim() < z_t.dim():
                sigma_t = sigma_t.unsqueeze(-1)
            score_pred = -noise_pred / sigma_t.clamp(min=1e-8)

            # ---- Loss ------------------------------------------------------
            loss: Tensor = self.loss_fn(score_pred, u, t)

            # ---- Backward + optimiser step ---------------------------------
            self.optimizer.zero_grad(set_to_none=True)
            loss.backward()
            nn.utils.clip_grad_norm_(self.score_net.parameters(), max_norm=1.0)
            self.optimizer.step()
            self.ema.step(self.score_net)

            loss_val: float = loss.item()
            loss_accum += loss_val
            n_logged += 1
            last_loss = loss_val

            # ---- Logging ---------------------------------------------------
            if local_step % self.log_freq == 0:
                mean_loss = loss_accum / n_logged
                logger.info(
                    "h=%d  step=%d  loss=%.6f  mean_loss=%.6f",
                    h, self._global_step, loss_val, mean_loss,
                )
                if writer is not None:
                    writer.add_scalar(f"train/loss_h{h}", loss_val, self._global_step)
                    writer.add_scalar(
                        f"train/mean_loss_h{h}", mean_loss, self._global_step
                    )
                loss_accum = 0.0
                n_logged = 0

            # ---- Checkpoint ------------------------------------------------
            if local_step % self.save_freq == 0:
                ckpt_path = self._default_ckpt_path(h, self._global_step)
                self.save(ckpt_path, h)
                logger.info("Checkpoint saved: %s", ckpt_path)

            # ---- Periodic replay refresh (every 10k steps, h > 1) ----------
            if h > 1 and local_step % 10_000 == 0:
                n_refresh = min(self.replay_buffer_size // 4, 2 * self.batch_size)
                self._refresh_replay_buffer(
                    buffer=buf,
                    h=h,
                    dataset=dataset,
                    teacher=teacher_fn,
                    device=device,
                    n_samples=n_refresh,
                )

        # Step (e): freeze EMA copy as teacher for next stage
        self._freeze_stage(h)

        final_loss = last_loss
        return {"final_loss": final_loss, "steps": self.steps_per_horizon}

    # ------------------------------------------------------------------
    # Replay buffer management
    # ------------------------------------------------------------------

    def _refresh_replay_buffer(
        self,
        buffer: SuffixReplayBuffer,
        h: int,
        dataset: TransitionDataset,
        teacher: Optional[Callable],
        device: torch.device,
        n_samples: int,
    ) -> None:
        """Populate *buffer* with n_samples fresh teacher-generated suffixes.

        For each sample:
          1. Draw a random transition (s, a, r, s', a') from D.
          2. Compute x' = (s', a').
          3. Call the teacher to generate a clean suffix W_+ of length h-1
             conditioned on x'.
          4. Store (x', W_+) in the buffer.

        Args:
            buffer:    The :class:`SuffixReplayBuffer` to fill.
            h:         Current horizon (suffix horizon = h-1).
            dataset:   Offline dataset for drawing conditioning contexts.
            teacher:   Callable wrapping the frozen teacher score network.
                       Signature: ``(z_t, x_cond, t) -> noise_pred``.
                       If None the buffer is left unchanged.
            device:    Compute device.
            n_samples: Number of (x', W_+) pairs to generate.
        """
        if teacher is None:
            return
        if h <= 1:
            return

        suffix_horizon = h - 1
        token_dim: int = diffusion_token_dim(self.diffusion)
        N = len(dataset)

        self.diffusion.to(device)

        for _ in range(n_samples):
            # Random transition from dataset
            idx = int(torch.randint(0, N, (1,)).item())
            batch_item = dataset[idx]
            next_state: Tensor = batch_item.next_state.to(device)  # (obs_dim,)

            # Sample a' ~ π_e(·|s') — not needed here since we just need x_cond
            # For replay, x' encodes the next-state only for conditioning:
            # we treat x_cond = (s', zeros_for_action) for teacher conditioning.
            # When the trainer later retrieves this suffix it pairs it with the
            # live a' sampled at training time, consistent with the BPD paper's
            # remark that the replay key is x' = s' (the state uniquely indexes
            # the conditional buffer entry).
            obs_dim = next_state.shape[0]
            # Key for the buffer is the raw next_state vector (unique per s').
            x_prime_key = next_state  # (obs_dim,)

            # Build x_cond for teacher: we need (s', a') but use zero-action
            # placeholder for suffix generation (teacher was trained on (s',a')
            # conditioning at horizon h-1).
            act_dim = dataset.act_dim
            x_cond = torch.cat(
                [next_state, torch.zeros(act_dim, device=device)], dim=0
            ).unsqueeze(0)  # (1, obs_dim + act_dim)

            # Generate clean suffix via full teacher reverse chain
            with torch.no_grad():
                suffix = self.diffusion.p_sample_loop(
                    score_net=teacher,
                    x=x_cond,
                    h=suffix_horizon,
                    batch_size=1,
                    device=device,
                )  # (1, suffix_horizon, token_dim)
            suffix = suffix.squeeze(0)  # (suffix_horizon, token_dim)

            buffer.add(x_prime_key, suffix)

    # ------------------------------------------------------------------
    # Teacher management
    # ------------------------------------------------------------------

    def _teacher_score_fn(self, h: int) -> Optional[Callable]:
        """Return a callable wrapping the frozen teacher for stage h-1.

        The teacher for stage h is the EMA-frozen score network from stage h-1.
        Returns ``None`` for h=1 (no teacher exists yet).

        The returned callable matches the ScoreNet protocol expected by
        :meth:`~bpd.models.diffusion.BlockwiseDiffusion.p_sample_loop`:
            ``(z_t: Tensor, x: Tensor, t: Tensor) -> Tensor``

        Args:
            h: Current training horizon (1-based).

        Returns:
            Frozen teacher callable or None.
        """
        if h <= 1:
            return None

        teacher_h = h - 1
        if teacher_h not in self._teachers:
            # This should not happen in normal sequential training, but fall
            # back to a copy of the live EMA shadow if the teacher is missing.
            logger.warning(
                "Teacher for h=%d not found in registry; "
                "falling back to current EMA shadow (may degrade quality).",
                teacher_h,
            )
            frozen = copy.deepcopy(self.ema.shadow)
            frozen.eval()
            frozen.requires_grad_(False)
            self._teachers[teacher_h] = frozen

        teacher_net: nn.Module = self._teachers[teacher_h]

        # Wrap to inject the fixed horizon h-1 into the score network call
        # so it matches the 4-argument signature (z, x, t, h).
        def _teacher_call(z_t: Tensor, x: Tensor, t: Tensor) -> Tensor:
            return teacher_net(z_t, x, t, teacher_h)

        return _teacher_call

    def _freeze_stage(self, h: int) -> None:
        """Store a frozen copy of the EMA shadow as the teacher for horizon h.

        Called at the end of :meth:`train_stage` to make stage-h teacher
        available for stage h+1.
        """
        frozen = copy.deepcopy(self.ema.shadow)
        frozen.eval()
        frozen.requires_grad_(False)
        self._teachers[h] = frozen
        logger.debug("Frozen teacher registered for horizon h=%d.", h)

    # ------------------------------------------------------------------
    # Training target construction
    # ------------------------------------------------------------------

    def _build_training_targets(
        self,
        h: int,
        rewards: Tensor,        # (B,)
        next_states: Tensor,    # (B, obs_dim)
        next_actions: Tensor,   # (B, act_dim)
        states: Tensor,         # (B, obs_dim)
        actions: Tensor,        # (B, act_dim)
        use_push: Tensor,       # (B,) bool
        replay_buf: Optional[SuffixReplayBuffer],
        teacher_fn: Optional[Callable],
        device: torch.device,
    ) -> Tuple[Tensor, Tensor]:
        """Construct clean path tensors w and conditioning x_cond for each batch item.

        For each item b in the batch:
          - stop branch (use_push[b]=False or h=1):
                w[b] = stop_h(y_b)      # (h, token_dim)
          - push branch (use_push[b]=True and h>1):
                w[b] = push_h(y_b, W+_b)  # (h, token_dim)
                where W+_b is retrieved from the replay buffer, or freshly
                generated by the teacher if not cached.

        Conditioning: x_cond[b] = (s_b, a_b)  – the current state-action,
        as per Eq. 10 of the BPD paper where the model is conditioned on x=(s,a).

        Args:
            h:            Current horizon.
            rewards:      (B,) reward tensors.
            next_states:  (B, obs_dim) next-state tensors.
            next_actions: (B, act_dim) next-action tensors from π_e.
            states:       (B, obs_dim) current state tensors.
            actions:      (B, act_dim) current action tensors (from dataset).
            use_push:     (B,) boolean mask; True → push branch.
            replay_buf:   Replay buffer for suffixes (None when h=1).
            teacher_fn:   Frozen teacher callable (None when h=1).
            device:       Compute device.

        Returns:
            Tuple ``(w, x_cond)`` where:
              * w       has shape (B, h, token_dim)
              * x_cond has shape (B, obs_dim + act_dim)
        """
        B = rewards.shape[0]
        token_dim_val: int = diffusion_token_dim(self.diffusion)
        obs_dim = next_states.shape[1]
        act_dim = next_actions.shape[1]

        # Build token y = (r, s', a') for each batch item  [Eq. 7]
        tokens: List[Tensor] = []
        for b in range(B):
            tok = encode_token(rewards[b], next_states[b], next_actions[b])
            tokens.append(tok)
        # tokens: list of B tensors, each (token_dim,)

        w_list: List[Tensor] = []
        for b in range(B):
            y_b = tokens[b].to(device)  # (token_dim,)

            if not use_push[b].item():
                # Stop branch: w = stop_h(y)
                w_b, _ = stop_map(y_b, h)  # (h, token_dim)
            else:
                # Push branch: retrieve or generate teacher suffix
                # Key is the next state (s'_b, a'_b concatenated)
                x_prime_b = torch.cat(
                    [next_states[b], next_actions[b]], dim=0
                ).to(device)  # (obs_dim + act_dim,)

                suffix: Optional[Tensor] = None
                if replay_buf is not None:
                    suffix = replay_buf.sample_or_none(x_prime_b)
                    if suffix is not None:
                        suffix = suffix.to(device)

                if suffix is None:
                    # Generate fresh suffix from teacher reverse chain
                    suffix = self._generate_teacher_suffix(
                        h=h,
                        x_prime=x_prime_b,
                        teacher_fn=teacher_fn,
                        device=device,
                    )
                    # Store in buffer for future reuse
                    if replay_buf is not None:
                        replay_buf.add(x_prime_b, suffix)

                # suffix: (h-1, token_dim)
                # Push: w = (y, suffix_0, ..., suffix_{h-2})
                pad_mask_suffix = torch.zeros(
                    h - 1, dtype=torch.bool, device=device
                )  # placeholder mask (no padding in teacher suffix)
                w_b, _ = push_map(y_b, suffix, pad_mask_suffix)  # (h, token_dim)

            w_list.append(w_b)

        w = torch.stack(w_list, dim=0)  # (B, h, token_dim)

        # Conditioning: x_cond = (s, a) for each transition  [Eq. 10]
        x_cond = torch.cat([states, actions], dim=1)  # (B, obs_dim + act_dim)

        return w, x_cond

    def _generate_teacher_suffix(
        self,
        h: int,
        x_prime: Tensor,
        teacher_fn: Optional[Callable],
        device: torch.device,
    ) -> Tensor:
        """Generate a clean suffix of length h-1 from the teacher network.

        Runs the full DDPM reverse chain from t=T to t=1 using the frozen
        teacher score network, conditioned on x'.

        Args:
            h:          Current horizon (suffix horizon = h-1).
            x_prime:    Conditioning x' = (s', a') of shape (obs_dim+act_dim,).
            teacher_fn: Frozen teacher callable.
            device:     Compute device.

        Returns:
            Clean suffix tensor of shape (h-1, token_dim).

        Raises:
            RuntimeError: If teacher_fn is None (only valid for h>1).
        """
        if teacher_fn is None:
            raise RuntimeError(
                "_generate_teacher_suffix called with no teacher (h=1 path)."
            )
        suffix_horizon = h - 1
        x_cond = x_prime.unsqueeze(0)  # (1, obs_dim + act_dim)

        with torch.no_grad():
            suffix = self.diffusion.p_sample_loop(
                score_net=teacher_fn,
                x=x_cond,
                h=suffix_horizon,
                batch_size=1,
                device=device,
            )  # (1, suffix_horizon, token_dim)
        return suffix.squeeze(0)  # (suffix_horizon, token_dim)

    # ------------------------------------------------------------------
    # Data sampling
    # ------------------------------------------------------------------

    def _sample_batch(
        self,
        dataset: TransitionDataset,
        eval_policy_fn: Callable[[Tensor], Tensor],
        device: torch.device,
    ) -> Tuple[Tensor, Tensor, Tensor, Tensor, Tensor]:
        """Sample a random mini-batch of transitions from the offline dataset.

        Queries π_e to obtain next-actions a' ~ π_e(·|s') for each sample.

        Args:
            dataset:        Offline transition dataset D.
            eval_policy_fn: Evaluation policy callable (s' → a').
            device:         Target device.

        Returns:
            Tuple (states, actions, rewards, next_states, next_actions), each
            of shape (B, dim) or (B,) as appropriate.
        """
        N = len(dataset)
        indices = torch.randint(0, N, (self.batch_size,))

        states_list: List[Tensor] = []
        actions_list: List[Tensor] = []
        rewards_list: List[Tensor] = []
        next_states_list: List[Tensor] = []
        next_actions_list: List[Tensor] = []

        for idx in indices.tolist():
            item = dataset[idx]
            states_list.append(item.state)
            actions_list.append(item.action)
            rewards_list.append(item.reward.unsqueeze(0) if item.reward.dim() == 0 else item.reward)
            next_states_list.append(item.next_state)

        states = torch.stack(states_list, dim=0).to(device)         # (B, obs_dim)
        actions = torch.stack(actions_list, dim=0).to(device)       # (B, act_dim)
        rewards = torch.cat(rewards_list, dim=0).to(device)         # (B,)
        next_states = torch.stack(next_states_list, dim=0).to(device)  # (B, obs_dim)

        # Evaluate policy in a batch-friendly way: stack → call → unstack
        with torch.no_grad():
            # Try batched call first; fall back to per-sample if it fails
            try:
                next_actions = eval_policy_fn(next_states)  # (B, act_dim)
            except Exception:
                na_list: List[Tensor] = [
                    eval_policy_fn(next_states[b]) for b in range(self.batch_size)
                ]
                next_actions = torch.stack(na_list, dim=0)
        next_actions = next_actions.to(device)  # (B, act_dim)

        return states, actions, rewards, next_states, next_actions

